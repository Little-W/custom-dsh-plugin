// src/host/knowledge/store.js
//
// 知识库落盘层：教训 JSON、生成技能索引与 SKILL.md 的读写。
//
// 边界：本文件只负责「字节 ↔ 对象」，不判断知识是否值得写、不生成检索摘要、
// 不注册技能。所有写入采用「临时文件 + rename」的原子替换；同一进程内的
// 读改写（教训合并、索引更新）按 key 串行，避免并发工具调用互相覆盖。
import { mkdir, readFile, readdir, rename, stat, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { randomBytes } from 'node:crypto';
import { KNOWLEDGE_SCHEMA_VERSION, LESSON_ID_PATTERN, lessonPathOf, lessonsDirOf, knowledgeRootOf, skillsIndexPathOf, userSkillPathOf, userSkillsRootOf, } from './constants.js';
/** 是否为普通对象（索引/教训结构校验用）。 */
function isPlainObject(value) {
    return value !== null && typeof value === 'object' && !Array.isArray(value);
}
/** 空索引结构。 */
function emptyIndex() {
    return { schemaVersion: KNOWLEDGE_SCHEMA_VERSION, skills: {} };
}
/** YAML 双引号标量（JSON 字符串在 YAML 中等价；换行压成空格，元数据必须单行）。 */
function yamlScalar(value) {
    return JSON.stringify(String(value ?? '').replace(/\s+/g, ' ').trim());
}
/** 渲染 SKILL.md：YAML frontmatter（name/description/whenToUse）+ 正文。 */
export function renderSkillMarkdown(entry, content) {
    const lines = [
        '---',
        `name: ${yamlScalar(entry.name)}`,
        `description: ${yamlScalar(entry.description)}`,
    ];
    const whenToUse = String(entry.whenToUse ?? '').trim();
    if (whenToUse)
        lines.push(`whenToUse: ${yamlScalar(whenToUse)}`);
    lines.push('---');
    const body = String(content ?? '').trim();
    return `${lines.join('\n')}\n\n<!-- Generated by dsh-visual-workflow knowledge component. Re-running wf_knowledge_capture with the same name updates this file. -->\n\n${body}\n`;
}
/** 去掉 SKILL.md 的 YAML frontmatter，返回技能正文（供运行期技能注册）。 */
export function stripFrontmatter(markdown) {
    const text = String(markdown ?? '');
    const match = text.match(/^---\r?\n[\s\S]*?\r?\n---[ \t]*\r?\n?/);
    return (match ? text.slice(match[0].length) : text).trim();
}
/** 教训条目结构校验（坏文件在列表时跳过，不阻断整个知识库）。 */
function isLesson(value) {
    return isPlainObject(value) && typeof value.id === 'string' && LESSON_ID_PATTERN.test(value.id) && value.kind === 'error_lesson';
}
/** 技能索引条目结构校验。 */
function isSkillEntry(value) {
    return isPlainObject(value) && typeof value.name === 'string' && value.name.length > 0;
}
export class KnowledgeStore {
    constructor(dataDir, options = {}) {
        const root = String(dataDir ?? '').trim();
        if (!root)
            throw new Error('KnowledgeStore: dataDir is required');
        this.dataDir = root;
        this.env = options.env ?? process.env;
        this.logger = options.logger ?? { warn: () => { } };
        this.root = knowledgeRootOf(root);
        this.lessonsDir = lessonsDirOf(root);
        this.indexPath = skillsIndexPathOf(root);
        this.skillsRoot = userSkillsRootOf(this.env);
        this.locks = new Map();
    }
    /** 建立必要的目录（幂等）。 */
    async init() {
        await mkdir(this.root, { recursive: true });
        await mkdir(this.lessonsDir, { recursive: true });
        return this;
    }
    /** 同 key 串行执行读改写（仅进程内；跨进程依赖原子 rename 的最终一致性）。 */
    async _withLock(key, task) {
        const previous = this.locks.get(key) ?? Promise.resolve();
        let release;
        const current = new Promise((resolve) => {
            release = resolve;
        });
        this.locks.set(key, current);
        await previous.catch(() => { });
        try {
            return await task();
        }
        finally {
            release();
            if (this.locks.get(key) === current)
                this.locks.delete(key);
        }
    }
    /** 原子写文本：同目录临时文件 + rename。 */
    async _writeAtomic(path, text) {
        const dir = dirname(path);
        await mkdir(dir, { recursive: true });
        const temp = join(dir, `.${basename(path)}.${process.pid}.${randomBytes(6).toString('hex')}.tmp`);
        await writeFile(temp, text, 'utf8');
        await rename(temp, path);
    }
    /** 读 JSON；文件不存在返回 undefined，损坏则抛错（调用方决定是否降级）。 */
    async _readJson(path) {
        let raw;
        try {
            raw = await readFile(path, 'utf8');
        }
        catch (error) {
            if (error?.code === 'ENOENT')
                return undefined;
            throw error;
        }
        return JSON.parse(raw);
    }
    // ── 生成技能索引 ────────────────────────────────────────────────────
    /** 读取索引（不存在/结构漂移时返回空索引）。 */
    async readIndex() {
        const raw = await this._readJson(this.indexPath);
        if (!isPlainObject(raw))
            return emptyIndex();
        const skills = isPlainObject(raw.skills) ? raw.skills : {};
        return { schemaVersion: Number(raw.schemaVersion) || KNOWLEDGE_SCHEMA_VERSION, skills };
    }
    /** 全部生成技能条目（按 updatedAt 降序；纯元数据，不含正文）。 */
    async listSkillEntries() {
        const index = await this.readIndex();
        return Object.values(index.skills)
            .filter(isSkillEntry)
            .map((entry) => ({ ...entry }))
            .sort((left, right) => String(right.updatedAt ?? '').localeCompare(String(left.updatedAt ?? '')));
    }
    /** 单个生成技能条目；不存在返回 null。 */
    async getSkillEntry(name) {
        const index = await this.readIndex();
        const entry = index.skills[String(name ?? '')];
        return isSkillEntry(entry) ? { ...entry } : null;
    }
    /** 写入/更新单个技能索引条目（串行读改写）。 */
    async putSkillEntry(entry) {
        return this._withLock('skills-index', async () => {
            const index = await this.readIndex();
            index.skills[entry.name] = { ...entry };
            await this._writeAtomic(this.indexPath, `${JSON.stringify(index, null, 2)}\n`);
            return { ...entry };
        });
    }
    /** 生成技能文件是否已存在。 */
    async hasSkillFile(name) {
        try {
            const info = await stat(userSkillPathOf(name, this.env));
            return info.isFile();
        }
        catch {
            return false;
        }
    }
    /** 生成技能文件路径。 */
    skillPathOf(name) {
        return userSkillPathOf(name, this.env);
    }
    /** 教训文件路径。 */
    lessonPathOf(id) {
        return lessonPathOf(this.dataDir, id);
    }
    /** 读取 SKILL.md 原文。 */
    async readSkillMarkdown(name) {
        return readFile(userSkillPathOf(name, this.env), 'utf8');
    }
    /** 文件是否带本组件的生成标记（索引丢失时据此恢复「这是生成技能」的判断）。 */
    async isGeneratedSkillFile(name) {
        try {
            const text = await this.readSkillMarkdown(name);
            return text.includes('Generated by dsh-visual-workflow knowledge component');
        }
        catch {
            return false;
        }
    }
    /** 读取技能正文（已去掉 frontmatter）。 */
    async readSkillBody(name) {
        return stripFrontmatter(await this.readSkillMarkdown(name));
    }
    /** 原子写入 SKILL.md。 */
    async writeSkillMarkdown(name, markdown) {
        await this._writeAtomic(userSkillPathOf(name, this.env), markdown);
    }
    // ── 错误教训 ────────────────────────────────────────────────────────
    /** 全部教训（按 updatedAt 降序；损坏文件跳过并记日志）。 */
    async listLessons() {
        let names;
        try {
            names = await readdir(this.lessonsDir);
        }
        catch (error) {
            if (error?.code === 'ENOENT')
                return [];
            throw error;
        }
        const lessons = [];
        for (const name of names) {
            if (!name.endsWith('.json'))
                continue;
            const path = join(this.lessonsDir, name);
            try {
                const value = await this._readJson(path);
                if (isLesson(value))
                    lessons.push(value);
            }
            catch (error) {
                this.logger.warn?.(`[visual-workflow] knowledge: skipped unreadable lesson ${path}: ${error?.message ?? error}`);
            }
        }
        return lessons.sort((left, right) => String(right.updatedAt ?? '').localeCompare(String(left.updatedAt ?? '')));
    }
    /** 单个教训；id 非法或不存在返回 null。 */
    async getLesson(id) {
        if (!LESSON_ID_PATTERN.test(String(id ?? '')))
            return null;
        try {
            const value = await this._readJson(join(this.lessonsDir, `${id}.json`));
            return isLesson(value) ? value : null;
        }
        catch (error) {
            this.logger.warn?.(`[visual-workflow] knowledge: cannot read lesson ${id}: ${error?.message ?? error}`);
            return null;
        }
    }
    /** 原子写入教训（调用方负责 id 与结构）。 */
    async writeLesson(lesson) {
        await this._writeAtomic(join(this.lessonsDir, `${lesson.id}.json`), `${JSON.stringify(lesson, null, 2)}\n`);
        return lesson;
    }
    /**
     * 教训的串行读改写：updater 收到 null（新建）或既有条目，返回新条目。
     * 返回 { lesson, created }；合并计数与历史截断由调用方在 updater 内决定。
     */
    async updateLesson(id, updater) {
        if (!LESSON_ID_PATTERN.test(String(id ?? '')))
            throw new Error(`invalid lesson id "${id}"`);
        return this._withLock(`lesson:${id}`, async () => {
            const existing = await this.getLesson(id);
            const next = await updater(existing);
            if (!isLesson(next))
                throw new Error(`lesson updater returned an invalid lesson for "${id}"`);
            await this.writeLesson(next);
            return { lesson: next, created: existing === null };
        });
    }
}
